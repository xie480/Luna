package org.yilena.luna.mq.consumer;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.apache.rocketmq.spring.annotation.RocketMQMessageListener;
import org.apache.rocketmq.spring.core.RocketMQListener;
import org.springframework.stereotype.Component;
import org.yilena.luna.constants.RocketMqConstant;
import org.yilena.luna.mq.dto.SummaryMessage;
import org.yilena.luna.service.TaskOrchestratorService;
import org.yilena.luna.service.model.SummaryOrchestrationResult;

/**
 * 上下文摘要消费者，负责消费摘要任务消息并触发上下文摘要编排流程。
 */
@Slf4j
@Component
@RequiredArgsConstructor
@RocketMQMessageListener(topic = RocketMqConstant.TOPIC_SUMMARY, consumerGroup = RocketMqConstant.GROUP_SUMMARY)
public class ContextSummaryConsumer implements RocketMQListener<SummaryMessage> {

    /**
     * 摘要编排服务，用于生成叙事摘要和状态快照。
     */
    private final TaskOrchestratorService taskOrchestratorService;

    @Override
    public void onMessage(SummaryMessage msg) {
        /**
         * 消息为空或缺失会话键时直接丢弃，避免无意义的摘要任务进入编排链路。
         */
        if (msg == null || msg.getSessionKey() == null || msg.getSessionKey().isBlank()) {
            return;
        }
        String sessionKey = msg.getSessionKey();
        try {
            /**
             * 基于会话和当前对话内容执行摘要编排，并记录摘要产物是否生成成功。
             */
            SummaryOrchestrationResult summaryOrchestrationResult = taskOrchestratorService.orchestrateSummary(
                    sessionKey,
                    msg.getUserInput(),
                    msg.getAssistantReply(),
                    null,
                    java.util.List.of(),
                    java.util.List.of(),
                    null,
                    true,
                    firstNonBlank(msg.getTriggerSource(), "MQ_SUMMARY")
            );
            String narrative = summaryOrchestrationResult == null || summaryOrchestrationResult.getSummaryResult() == null
                    ? ""
                    : summaryOrchestrationResult.getSummaryResult().getNarrativeSummary();
            int snapshotSize = summaryOrchestrationResult == null
                    || summaryOrchestrationResult.getSummaryResult() == null
                    || summaryOrchestrationResult.getSummaryResult().getStateSnapshot() == null
                    ? 0
                    : summaryOrchestrationResult.getSummaryResult().getStateSnapshot().size();
            log.info("context summary generated by TaskOrchestrator, sessionKey={}, narrativePresent={}, snapshotSize={}",
                    sessionKey, narrative != null && !narrative.isBlank(), snapshotSize);
        } catch (Exception ex) {
            /**
             * 摘要编排异常仅记录日志，避免消息消费线程被异常打断。
             */
            log.error("context summary failed, sessionKey={}, error={}", sessionKey, ex.getMessage(), ex);
        }
    }

    /**
     * 返回第一个非空字符串，用于补齐触发来源标识。
     */
    private String firstNonBlank(String first, String second) {
        if (first != null && !first.isBlank()) {
            return first;
        }
        if (second != null && !second.isBlank()) {
            return second;
        }
        return "";
    }
}
