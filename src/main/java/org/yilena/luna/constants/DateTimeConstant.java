package org.yilena.luna.constants;

/**
 * 日期时间格式常量类，统一维护系统内常用的日期与时间格式模板。
 */
public class DateTimeConstant {

    /**
     * 日期时间格式，精确到秒，格式为 yyyy-MM-dd HH:mm:ss。
     */
    public static final String FORMAT_YYYYMMDDHHMMSS = "yyyy-MM-dd HH:mm:ss";

    /**
     * 日期时间格式，精确到分钟，格式为 yyyy-MM-dd HH:mm。
     */
    public static final String FORMAT_YYYYMMDDHHMM = "yyyy-MM-dd HH:mm";

    /**
     * 日期格式，格式为 yyyy-MM-dd。
     */
    public static final String FORMAT_YYYYMMDD = "yyyy-MM-dd";

    /**
     * 年月格式，格式为 yyyy-MM。
     */
    public static final String FORMAT_YYYYMM = "yyyy-MM";

    /**
     * 日期格式，斜杠分隔，格式为 yyyy/MM/dd。
     */
    public static final String FORMAT_YYYYMMDD_ITALIC = "yyyy/MM/dd";

    /**
     * 年月格式，斜杠分隔，格式为 yyyy/MM。
     */
    public static final String FORMAT_YYYYMM_ITALIC = "yyyy/MM";

    /**
     * 年格式，格式为 yyyy。
     */
    public static final String FORMAT_YYYY = "yyyy";

    /**
     * 时间格式，精确到秒，格式为 HH:mm:ss。
     */
    public static final String FORMAT_HHMMSS = "HH:mm:ss";

    /**
     * 月份格式，格式为 MM。
     */
    public static final String FORMAT_MM = "MM";

    /**
     * 紧凑型日期时间格式，精确到分钟，格式为 yyyyMMddHHmm。
     */
    public static final String FORMAT_YYYYMMDDHHMM_NO_SEPARATOR = "yyyyMMddHHmm";
}
